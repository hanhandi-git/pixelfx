#!/usr/bin/env node
// Regenerate the registry (src/fx/index.js) and the catalog (docs/CATALOG.md) from the effect files.
//
//   node tools/index.mjs

import { writeFileSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT, FX_DIR, allIds, loadEffect, ENCOUNTER_DIR, allEncounterIds, loadEncounter } from "./lib/fxlib.mjs";
import { categories } from "../src/fx/categories.js";
import { originOf } from "../src/fx/provenance.js";

const metas = [];
for (const id of allIds()) {
  try {
    metas.push({ id, provenance: originOf(id), ...(await loadEffect(id)).meta });
  } catch (e) {
    console.error(`skipping ${id}: ${String(e.message ?? e).split("\n")[0]}`);
  }
}
const ids = metas.map((m) => m.id);
const order = new Map(categories.map((c, i) => [c.id, i]));
const rank = (id) => order.get(id.split("/")[0]) ?? 99;
ids.sort((a, b) => rank(a) - rank(b) || a.localeCompare(b));
metas.sort((a, b) => rank(a.id) - rank(b.id) || a.id.localeCompare(b.id));

const ident = (id) => id.replace(/[^a-z0-9]+/gi, "_");
const lines = [
  "// Generated by tools/index.mjs: every effect, by id. Don't edit; run `node tools/index.mjs`.",
  "",
  ...ids.map((id) => `import * as ${ident(id)} from "./${id}.js";`),
  "",
  `export { categories } from "./categories.js";`,
  `export { originOf, ORIGINS, ORIGINAL_EFFECTS } from "./provenance.js";`,
  "",
  "export const effects = {",
  ...ids.map((id) => `  "${id}": ${ident(id)},`),
  "};",
  "",
  "export const provenance = {",
  ...ids.map((id) => `  "${id}": "${originOf(id)}",`),
  "};",
  "",
];
writeFileSync(join(FX_DIR, "index.js"), lines.join("\n"));

const newCount = ids.filter((id) => originOf(id) === "new").length;
const md = [
  "# Catalog",
  "",
  `${ids.length} effects in ${categories.filter((c) => metas.some((m) => m.id.startsWith(c.id + "/"))).length} categories: ${ids.length - newCount} original and ${newCount} new. Every one is a file in`,
  "`src/fx/<category>/<name>.js`; render any of them with `node tools/render.mjs <id> --gif`.",
  "",
];
for (const c of categories) {
  const list = metas.filter((m) => m.id.startsWith(c.id + "/"));
  if (!list.length) continue;
  md.push(`## ${c.name}`, "", `${c.blurb}.`, "", "| effect | id | source | kind | play | size | what it does |", "|---|---|---|---|---|---|---|");
  for (const m of list)
    md.push(`| ${m.name} | \`${m.id}\` | ${m.provenance} | ${m.kind ?? "effect"} | ${m.loop ? "loop" : "one-shot"} ${+m.duration.toFixed(2)}s | ${m.size[0]}×${m.size[1]} | ${m.desc.replace(/\|/g, "\\|")} |`);
  md.push("");
}
writeFileSync(join(ROOT, "docs", "CATALOG.md"), md.join("\n"));

// encounters: a generated registry and a short catalog of their timelines
const encs = [];
for (const id of allEncounterIds()) {
  try {
    const fx = await loadEncounter(id);
    encs.push({ id, ...fx.meta, phases: fx.mod.encounter.phases ?? [], mobs: fx.mod.encounter.mobs ?? [] });
  } catch (e) {
    console.error(`skipping encounter ${id}: ${String(e.message ?? e).split("\n")[0]}`);
  }
}
const encIdent = (id) => id.replace(/[^a-z0-9]+/gi, "_");
const encLines = [
  "// Generated by tools/index.mjs: every encounter, by id. Don't edit; run `node tools/index.mjs`.",
  "",
  ...encs.map((e) => `import * as ${encIdent(e.id)} from "./${e.id}.js";`),
  "",
  "export const encounters = {",
  ...encs.map((e) => `  "${e.id}": ${encIdent(e.id)},`),
  "};",
  "",
];
writeFileSync(join(ENCOUNTER_DIR, "index.js"), encLines.join("\n"));
const encMd = [
  "# Encounters",
  "",
  `${encs.length} choreographed encounters in \`src/encounters/\`. Render one with \`node tools/encounter.mjs <id> --mp4\`.`,
  "",
  "An encounter places a map, a hero, minions, a boss and that boss's attack effects on one timeline. The units and",
  "attacks are ordinary effects from `src/fx/`; the encounter only says when they happen and what the fight calls them.",
  "",
  "| encounter | map | boss | minions | length | what it does |",
  "|---|---|---|---|---|---|",
  ...encs.map((e) => `| ${e.name} | \`${e.map ?? "?"}\` | ${e.boss ? `\`${e.boss}\`` : "—"} | ${(e.mobs ?? []).length || "—"} | ${+e.duration.toFixed(1)}s | ${e.desc.replace(/\|/g, "\\|")} |`),
  "",
];
writeFileSync(join(ROOT, "docs", "ENCOUNTERS.md"), encMd.join("\n"));
console.log(`${ids.length} effects (${ids.length - newCount} original, ${newCount} new) -> src/fx/index.js, docs/CATALOG.md`);
console.log(`${encs.length} encounters -> src/encounters/index.js, docs/ENCOUNTERS.md`);

// README: the count and the category table
const readme = join(ROOT, "README.md");
const rows = categories
  .map((c) => [c, metas.filter((m) => m.id.startsWith(c.id + "/"))])
  .filter(([, list]) => list.length)
  .map(([c, list]) => `| **${c.name}** | ${list.length} | ${list.slice(0, 6).map((m) => m.name.toLowerCase()).join(", ")}${list.length > 6 ? "…" : ""} |`);
const table = ["| category | effects | some of them |", "|---|---|---|", ...rows].join("\n");
let text = readFileSync(readme, "utf8");
text = text.replace(/<!-- count -->[\s\S]*?<!-- \/count -->/, `<!-- count -->${ids.length}<!-- /count -->`);
text = text.replace(/<!-- original-count -->[\s\S]*?<!-- \/original-count -->/, `<!-- original-count -->${ids.length - newCount}<!-- /original-count -->`);
text = text.replace(/<!-- new-count -->[\s\S]*?<!-- \/new-count -->/, `<!-- new-count -->${newCount}<!-- /new-count -->`);
text = text.replace(/<!-- catalog -->[\s\S]*?<!-- \/catalog -->/, `<!-- catalog -->\n${table}\n<!-- /catalog -->`);
writeFileSync(readme, text);
